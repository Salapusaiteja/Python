x = 10
print(x)  # 10
# Add and assign
x += 5
print(x)  # 15
# Subtract and assign
x -= 3
print(x)  # 12
# Multiply and assign
x *= 2
print(x)  # 24
# Divide and assign
x /= 4
print(x)  # 6.0
# Floor divide and assign
x //= 2
print(x)  # 3.0
# Modulus and assign
x %= 2
print(x)  # 1.0
# Exponentiation and assign
x **= 3
print(x)  # 1.0
